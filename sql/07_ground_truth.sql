USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ONTOLOGY_WH;

CREATE OR REPLACE VIEW ONTOLOGY_DEMO.AGENTS.DEMO_GROUND_TRUTH AS
WITH po AS (
  SELECT p.*, i.CATEGORY_CODE, c.LEAF_CATEGORY, c.MATERIAL_TYPE, c.CATEGORY_FAMILY, c.CATEGORY_GROUP,
         s.ULTIMATE_PARENT, s.SOURCING_REGION
  FROM ONTOLOGY_DEMO.RAW.PURCHASE_ORDERS p
  JOIN ONTOLOGY_DEMO.RAW.ITEMS i ON i.ITEM_ID = p.ITEM_ID
  JOIN ONTOLOGY_DEMO.ONTOLOGY.VW_ONT_CATEGORY_PATH c ON c.CATEGORY_CODE = i.CATEGORY_CODE
  JOIN ONTOLOGY_DEMO.ONTOLOGY.VW_ONT_SUPPLIER_HIERARCHY s ON s.SUPPLIER_ID = p.SUPPLIER_ID
),
expand AS (
  SELECT x.CONCEPT_ID, x.CATEGORY_CODE FROM ONTOLOGY_DEMO.ONTOLOGY.VW_ONT_CONCEPT_EXPANSION x
)
SELECT 'Q1' AS Q, 'Total spend on electronic components in 2026 (hierarchy roll-up)' AS QUESTION,
       SUM(AMOUNT_USD) AS ANSWER_USD
FROM po
WHERE YEAR(PO_DATE) = 2026 AND CATEGORY_CODE IN (SELECT CATEGORY_CODE FROM expand WHERE CONCEPT_ID = 'C:ELEC')
UNION ALL
SELECT 'Q2', 'Total spend on capacitors (all types), 2026', SUM(AMOUNT_USD)
FROM po WHERE YEAR(PO_DATE) = 2026 AND LEAF_CATEGORY IN ('Ceramic Capacitor','Electrolytic Capacitor')
UNION ALL
SELECT 'Q3', 'Spend with Orion Electronics Group incl. all subsidiaries (all time)', SUM(AMOUNT_USD)
FROM po WHERE ULTIMATE_PARENT = 'Orion Electronics Group'
UNION ALL
SELECT 'Q4', 'Steel-price-exposed material spend 2026 (composite concept)', SUM(AMOUNT_USD)
FROM po
WHERE YEAR(PO_DATE) = 2026 AND CATEGORY_CODE IN (SELECT CATEGORY_CODE FROM expand WHERE CONCEPT_ID = 'C:STEEL_EXPOSED')
UNION ALL
SELECT 'Q5', 'APD / PPE spend 2026 (Bahasa synonym)', SUM(AMOUNT_USD)
FROM po WHERE YEAR(PO_DATE) = 2026 AND LEAF_CATEGORY = 'Personal Protective Equipment'
UNION ALL
SELECT 'Q6', 'Largest supplier group share of 2026 direct material spend (%)',
       MAX(share) FROM (
         SELECT ULTIMATE_PARENT, 100 * SUM(AMOUNT_USD) / SUM(SUM(AMOUNT_USD)) OVER () AS share
         FROM po WHERE YEAR(PO_DATE) = 2026 AND MATERIAL_TYPE = 'Direct Material' GROUP BY 1);

SELECT Q, QUESTION, ROUND(ANSWER_USD, 1) AS ANSWER FROM ONTOLOGY_DEMO.AGENTS.DEMO_GROUND_TRUTH ORDER BY Q;

-- Group shares for Q6 in detail
SELECT s.ULTIMATE_PARENT, ROUND(SUM(p.AMOUNT_USD)) AS SPEND_2026,
       ROUND(100 * RATIO_TO_REPORT(SUM(p.AMOUNT_USD)) OVER (), 1) AS PCT_OF_DIRECT
FROM ONTOLOGY_DEMO.RAW.PURCHASE_ORDERS p
JOIN ONTOLOGY_DEMO.RAW.ITEMS i ON i.ITEM_ID = p.ITEM_ID
JOIN ONTOLOGY_DEMO.ONTOLOGY.VW_ONT_CATEGORY_PATH c ON c.CATEGORY_CODE = i.CATEGORY_CODE
JOIN ONTOLOGY_DEMO.ONTOLOGY.VW_ONT_SUPPLIER_HIERARCHY s ON s.SUPPLIER_ID = p.SUPPLIER_ID
WHERE YEAR(p.PO_DATE) = 2026 AND c.MATERIAL_TYPE = 'Direct Material'
GROUP BY 1 ORDER BY 2 DESC;
